import '../services/locale_provider.dart';

/// Every code-rendered piece of UI chrome text in the app, in English,
/// Spanish, German, Italian, Japanese, Korean, Dutch, French, and
/// Portuguese — cocktail/ingredient names are deliberately left out
/// (proper nouns that read the same, or close enough, in every language,
/// same as "Mojito" staying "Mojito" on a menu regardless of what
/// language the rest of it is in). The five in-game action buttons
/// (Cherry Bomb/Shake/Mega-Shake/Alcohol-Free/Menu) used to be wood signs
/// with their own English text painted in, so needed new art to
/// translate — they're plain photo icons now, with their labels (and
/// costs, where one applies) rendered here instead, so this is the only
/// place that needs touching for those.
///
/// Japanese/Korean text renders in whatever font Flutter falls back to
/// for those glyphs (see colorful_plank_text.dart's PlankFont values —
/// all Latin-script display faces with no CJK coverage), not the game's
/// own stylized lettering — readable, just visually plainer there than
/// the Latin-script languages.
///
/// [tr] falls back to the English string (or the raw key, if that's
/// somehow missing too) rather than ever showing a blank — a missing
/// translation should never be worse than the wrong language.
String tr(AppLocale locale, String key) {
  final map = switch (locale) {
    AppLocale.es => _es,
    AppLocale.de => _de,
    AppLocale.it => _it,
    AppLocale.ja => _ja,
    AppLocale.ko => _ko,
    AppLocale.nl => _nl,
    AppLocale.fr => _fr,
    AppLocale.pt => _pt,
    AppLocale.en => _en,
  };
  return map[key] ?? _en[key] ?? key;
}

